// Practice — one problem per slide, with a stepped solution behind a button.
//
// Every revealed solution follows the deck's five lines in the same order —
// pieces (with units AND signs), formula, rearrange with letters, substitute,
// answer with a unit — so the practice drills the METHOD and not just the
// arithmetic. For momentum the five lines carry three extra habits:
//   · pieces: every velocity gets a sign — right / east / forward = +,
//     left / west / backward = −;
//   · formula: a collision always starts from the standard equation
//     m₁v₁ᵢ + m₂v₂ᵢ = m₁v₁f + m₂v₂f, and the solution says which version the
//     story turns it into ("at rest" → a term vanishes; "stick together" →
//     one v_f, then factor);
//   · rearrange: each move is NAMED ("m₂ is multiplying v₂f → divide both
//     sides by m₂"), and every negative number goes in brackets when it is
//     substituted — minus a minus is a plus.
// The last line always says what the sign MEANS (negative = moving west /
// bouncing back).
//
// Rearrangements are MCQs (f3, c6); the calculations are typed boxes.
//
// Typed numeric answers: the engine marks by exact value, so "−2.51" and
// "-2.51" both match $-2.51$, but "2.51" does NOT. Every item whose answer has
// a direction therefore says "include the sign". Rounding variants (four and
// five significant figures, and the neighbouring three-s.f. values an early
// rounding produces) sit in `accept`.
//
