// Every revealed solution follows the deck's five lines in the same order —
// pieces (with units, signs and conversions), formula, rearrange with letters,
// substitute, answer with a unit — so the practice drills the METHOD and not
// just the arithmetic. For rotation the five lines carry four extra habits:
//   · pieces: turns × 2π → rad, diameter ÷ 2 → radius, cm ÷ 100 → m, and a
//     weight already in N is not × 9.8;
//   · formula: a kinematics item names the letter the question never
//     mentions, and so which of the four equations it uses;
//   · rearrange: each move is NAMED, and "× 2 undoes the ½";
//   · balance: the pivot goes on the support NOT asked about.
//
// Rearrangements are MCQs (f5, c11); the calculations are typed boxes.
//
// Typed numeric answers: the engine marks by exact value, so "−5.36" and
// "-5.36" both match $-5.36$, but "5.36" does NOT. Every item whose answer
// has a direction therefore says "include the sign". Rounding variants (four
// and five significant figures, and the neighbouring three-s.f. values an
// early rounding produces) sit in `accept`.
//
